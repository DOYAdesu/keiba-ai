def match_patterns(place_code, surface, distance, entries_df):
    """狙い目パターンに合致する馬を探す。

    entries_df: waku, corner_ratio, agari_rank 列を持つ DataFrame。
    返り値: (合致フラグの list, パターン名 or None)
    """
    for p_place, p_surface, p_dist, name, cond in PATTERNS:
        if (place_code, surface, int(distance or 0)) == (p_place, p_surface, p_dist):
            flags = []
            for _, r in entries_df.iterrows():
                try:
                    ok = (not np.isnan(r["waku"]) and not np.isnan(r["corner_ratio"])
                          and cond(r))
                except (TypeError, ValueError):
                    ok = False
                flags.append(bool(ok))
            return flags, name
    return [False] * len(entries_df), None
