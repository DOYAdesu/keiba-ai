# 外回り使用時の芝直線長 (新潟・京都・阪神は距離で内外が変わる)
OUTER_STRAIGHT = {
    "04": (659, {1600, 1800, 2000}),          # 新潟外回り
    "08": (404, {1400, 1600, 1800, 2200, 2400, 3000, 3200}),  # 京都外回り
    "09": (474, {1400, 1600, 1800, 2400, 2600, 3000}),        # 阪神外回り
}
NIIGATA_STRAIGHT_1000 = 1000  # 新潟の直線1000mコース


def geo_features(place_code, surface, distance):
    """(turn, straight_len, slope_level, turf_yoshiba) を返す。"""
    geo = PLACE_GEO.get(place_code)
    if geo is None:
        return np.nan, np.nan, np.nan, np.nan
    turn, s_turf, s_dirt, slope, yoshiba = geo

    if surface == "ダ":
        straight = s_dirt
    else:
        straight = s_turf
        if surface == "芝" and distance:
            d = int(distance)
            if place_code == "04" and d == 1000:
                straight = NIIGATA_STRAIGHT_1000
            else:
                outer = OUTER_STRAIGHT.get(place_code)
                if outer and d in outer[1]:
                    straight = outer[0]

    turf_yoshiba = yoshiba if surface == "芝" else 0
    return turn, straight, slope, turf_yoshiba


def turn_of(place_code):
    geo = PLACE_GEO.get(place_code)
    return geo[0] if geo else np.nan
